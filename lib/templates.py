def _hook_body(name: str, cfg: dict):
    # [round-4 D17] The hook's posture is filled into the SHARED HEADER, from
    # the body's own declaration, because the header's empty-payload check
    # runs before the body does. Derived rather than listed: a new advisory
    # hook that writes `FAIL_CLOSED=0` gets the right header automatically.
    #
    # [round-4 D3] Bodies below may carry the same `@@NAME@@` placeholders the
    # shared header does - secrets-gate's walker is the other shell copy of
    # the command-position model. Filling them HERE, on the way out, is what
    # makes "one definition per substrate" a property of the code rather than
    # a comment: there is no second place to edit and therefore no second
    # place to forget, which is exactly how D3 happened.
    return _finish_hook(_hook_body_raw(name, cfg))


def _finish_hook(body):
    """Fill every emission-time placeholder, once, on the way out.

    Both the greenfield and the retrofit composition end here, so the retrofit
    wrapper can compare against the RAW `_HOOK_HEADER` while it splices, and
    neither path can emit a half-substituted hook. `None` passes through for
    the hooks a config does not enable.
    """
    if body is None:
        return None
    body = body.replace("@@POSTURE@@",
                        "0" if "\nFAIL_CLOSED=0" in body else "1")
    for _k, _v in _SHELL_SUBST.items():
        body = body.replace(_k, _v)
    # Check for OUR placeholder names, not for `@@`. A bare `@@` test would
    # refuse an install whose `commands.test` merely contains the string -
    # `grep '@@' file` is an ordinary command - and turn a guard against a
    # renamed placeholder into a config-shaped denial of service.
    for _k in tuple(_SHELL_SUBST) + ("@@POSTURE@@",):
        if _k in body:
            raise AssertionError(f"unfilled placeholder {_k} in an emitted hook")
    return body


