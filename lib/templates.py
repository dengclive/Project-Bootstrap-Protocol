# [round-4 D1/D2/D3/D7/D9] The command-position sets are interpolated from
# lib/cmdpos.py rather than written here. `_HOOK_HEADER` is a plain string,
# not an f-string - making it one would mean doubling every `${...}` in a
# 300-line shell body - so the substitution is by unique placeholder at the
# bottom of this block. Each `@@NAME@@` below is filled exactly once.
_HOOK_HEADER = """#!/usr/bin/env bash
# Generated by bootstrap-installer. Edit with care - security-relevant.
# Exit codes: 0 allow | 1 hook-internal error (tool proceeds) | 2 block.
#
# Security/correctness (Bootstrap-Protocol-v2-0-0.md 6.D checklist):
#  * No eval/dynamic execution: the Python fallback walks keys explicitly.
#  * stdin is consumed exactly once into $INPUT. The jq-less fallback now
#    receives it on the fallback process's OWN stdin [upstream P0-3a]. The
#    previous version passed it in the ENVIRONMENT; Linux caps a single env
#    var at 128 KiB, so any larger payload failed exec with rc 126, `|| true`
#    swallowed it, jget returned empty, and every parsing gate fell through
#    its `case` and ALLOWED. A 3 MB Write to .env is precisely the case that
#    matters. (Env-passing was itself the fix for an earlier bug where the
#    fallback re-read already-consumed stdin - it traded one silent failure
#    for another. Piping fixes both: fresh stdin, no size ceiling.)
#  * FAIL-CLOSED [upstream P0-3b]: with neither jq nor python3 on PATH, jget
#    used to return empty and every gate's `case` fell through to allow. A
#    security substrate must never degrade to allow, so blocking gates now
#    exit 2 with a loud reason. Advisory hooks set FAIL_CLOSED=0.
#  * Logging is never fatal [upstream P0-3c]: an unwritable CLAUDE_PROJECT_DIR
#    used to kill `mkdir -p` under `set -e`, yielding exit 1 = "hook error,
#    tool proceeds" - i.e. the read the gate exists to stop went through.
set -euo pipefail

# Blocking gates leave this at 1. Advisory/informational hooks set it to 0.
# The default is fail-closed on purpose: a hook that forgets to declare its
# posture gets the safe one.
#
# [round-4 D17] THE POSTURE IS BAKED IN HERE NOW, not declared in the body.
# It used to be `FAIL_CLOSED=1` here and `FAIL_CLOSED=0` in the body - but the
# empty-payload `hook_fail` below sits in this header, i.e. ABOVE the line
# that would have lowered the posture, so SIX advisory hooks exited 2 on an
# empty payload: format-lint-gate, spec-gate-entry, cost-log, drift-detector,
# task-done-alarm and decision-required-alarm. On a `Stop` event `exit 2`
# means "do not stop"; on spec-gate-entry, a UserPromptSubmit hook, it blocks
# the USER'S OWN PROMPT. An advisory hook that blocks is not advisory.
# Backlog J-19 recorded four of the six.
#
# The value is derived from the body's own `FAIL_CLOSED=0` declaration at
# emission time, so there is no second list of advisory hooks to drift.
FAIL_CLOSED=@@POSTURE@@

LOG="${CLAUDE_PROJECT_DIR:-.}/.claude/logs/hooks.log"
mkdir -p "$(dirname "$LOG")" 2>/dev/null || true
# [upstream P3] hooks.log had no rotation or size cap and grew without bound
# (a 1500-line file accumulated in the protocol's own tree and was eventually
# committed). It is gitignored and logs no credential values, so this was a
# disclosure/hygiene gap rather than a leak - but the 7-day purge the
# protocol advertises has to be implemented by something. One rotation at
# 1 MiB, keeping a single .1 generation.
_LOG_MAX=1048576
_rotate_log(){
  local sz
  # [lens A F10 / lens B 15] The guard is load-bearing, not defensive. A
  # fresh install has no .claude/logs/hooks.log, and redirections are applied
  # LEFT TO RIGHT: `wc -c <"$LOG" 2>/dev/null` reports the failing INPUT
  # redirection before `2>/dev/null` is in effect, so every hook printed
  # `...: No such file or directory` on its first run of a clean install -
  # shell-error noise attached to a security gate's first decision.
  [ -f "$LOG" ] || return 0
  sz="$({ wc -c <"$LOG"; } 2>/dev/null || echo 0)"
  case "$sz" in ''|*[!0-9]*) return 0 ;; esac
  if [ "$sz" -gt "$_LOG_MAX" ]; then
    mv -f "$LOG" "$LOG.1" 2>/dev/null || true
  fi
}
_rotate_log
log(){ printf '%s %s\\n' "$(date -u +%FT%TZ)" "$*" >>"$LOG" 2>/dev/null || true; }

# The single exit path for "this hook could not do its job". Never silent.
hook_fail(){
  log "FAIL $*"
  if [ "${FAIL_CLOSED:-1}" = "1" ]; then
    printf 'BLOCKED (fail-closed): %s\\n' "$*" >&2
    exit 2
  fi
  printf 'hook degraded: %s\\n' "$*" >&2
  exit 1
}
trap 'hook_fail "unexpected hook error at line $LINENO"' ERR

# [round-2 review F-301] Was `INPUT="$(cat || true)"`. The batch that closed
# the PATH-manipulation fail-open rewrote three helpers in pure bash and left
# the payload read itself forking `cat` - in the SHARED header, so ONE
# missing binary disabled all eleven hooks at once, in the direction that
# allows. Confirmed by execution: with a PATH holding jq, python3, grep, sed,
# tr and git but not `cat`, secrets-gate on `cat .env` and dependency-gate on
# `npm install evil` both returned rc=0. INPUT was empty, jq succeeds on
# empty input so hook_fail never fired, every jget returned empty and every
# gate fell through to allow - with no error line, no log entry and no
# hook_fail. A strictly better lever than the `tr`/`grep` that batch removed.
#
# `read -r -d ''` is a BUILTIN: it reads to NUL (which JSON cannot contain,
# so it reads to EOF), preserves newlines, and returns non-zero at EOF -
# hence the `|| true`, which is about EOF, not about tolerating failure.
IFS= read -r -d '' INPUT || true
# A payload that is empty when the harness always sends one means the read
# itself failed, which is the shape every fail-open in this class has taken.
# Fail CLOSED and say so, rather than letting the gates evaluate nothing.
if [ -z "$INPUT" ]; then
  hook_fail "empty hook payload on stdin (expected a JSON tool event)"
fi
have_jq(){ command -v jq >/dev/null 2>&1; }
have_py(){ command -v python3 >/dev/null 2>&1; }
# Kept in a variable and passed with `python3 -c` so the program does not
# occupy the fallback's stdin - that slot carries the payload now.
JGET_PY='
import json, sys
raw = sys.stdin.read()
try:
    d = json.loads(raw) if raw.strip() else {}
except Exception:
    sys.exit(0)
cur = d
for k in sys.argv[1].split("."):
    if isinstance(cur, dict) and k in cur:
        cur = cur[k]
    else:
        sys.exit(0)
# Render exactly like `jq -r "PATH // empty"`. Two deliberate details:
# booleans render lowercase (str(True) would emit "True" and silently fail
# every [ "$(jget ...)" = "true" ] guard - v2.5.0 review F3), and False
# renders as EMPTY because jq_s `//` treats false as absent. The two parsers
# must be the same function or the next boolean guard added diverges by
# substrate [upstream P3].
if cur is not None and not isinstance(cur, (dict, list)):
    if isinstance(cur, bool):
        sys.stdout.write("true" if cur else "")
    else:
        sys.stdout.write(str(cur))
'
# jget '.a.b' -> value at path, or empty. Fails closed if no parser WORKS.
#
# THE FALLBACK IS ON FAILURE, NOT ON ABSENCE [2026-07-31]. This used to read
# `if have_jq ... elif have_py`, which binds the choice of parser to whether a
# binary of that name EXISTS. `have_jq` is `command -v jq`: it cannot tell a
# working jq from a version-manager shim with no version resolved (asdf and
# mise both carry jq as a first-class tool - `asdf-jq`, mise registry
# `aqua:jqlang/jq` - and put their shim dir on PATH; the shim prints a
# "not installed" line and exits non-zero), a jq whose dynamic link is broken
# (`error while loading shared libraries: libonig.so.5`, the Alpine/slim-image
# shape), a non-executable file of the right name, or a different tool
# entirely. The old form then swallowed the failure with `|| true`, so jget
# returned EMPTY and every parsing gate fell through its `case` to ALLOW -
# with a perfectly good python3 sitting unused on the same PATH, and with the
# `elif` guaranteeing it was never reached.
#
# Executed on the emitted artifact, jq exiting 127 with python3 present:
# secrets-gate on `cat .env` returned rc=0 and dependency-gate on
# `npm install evil` returned rc=0 - both silent, both logged only the
# misleading "no path". That is upstream P0-3b's fail-open reopened through
# the SELECTOR rather than through absence: P0-3b fixed "no parser at all",
# and this is "a parser that does not work", which the presence test reports
# as success. A security substrate must never degrade to allow.
#
# So: try each parser in turn and accept its output only if it actually
# EXITED CLEAN. The parser is the LAST command in the pipeline, so its status
# is already the pipeline's - plain POSIX, no option needed. The header's
# `set -o pipefail` adds the reverse direction: a failed printf (SIGPIPE, if
# the parser dies before reading its input) also fails the pipeline, so a
# half-fed parse cannot pass as a clean one. Both parsers failing is now the
# same condition
# as neither being installed - hook_fail, which is fail-closed for a blocking
# gate and a logged degrade for an advisory one. `local` is declared on its
# own line: `local out="$(...)"` would mask the substitution's exit status
# behind `local`'s own, which is the bug this function is being fixed for.
jget(){
  local jqpath="$1"
  local out
  if have_jq; then
    if out="$(printf '%s' "$INPUT" | jq -r "$jqpath // empty" 2>/dev/null)"
    then
      printf '%s' "$out"
      return 0
    fi
  fi
  if have_py; then
    if out="$(printf '%s' "$INPUT" \\
              | python3 -c "$JGET_PY" "${jqpath#.}" 2>/dev/null)"
    then
      printf '%s' "$out"
      return 0
    fi
  fi
  hook_fail "no WORKING JSON parser (need jq or python3; one may be present but broken)"
}

# --- Command matching [upstream P1-4] -------------------------------------- #
# Four gates used to match a fixed-spacing literal SUBSTRING of the command.
# That failed in both directions at once. It missed `git  commit` (two
# spaces), a tab, `git --no-pager commit`, and `git -C /repo commit`; and it
# fired on `git commit` appearing anywhere at all - inside a shell comment, a
# quoted string, or a grep pattern. The second half is the dangerous one: it
# makes a full build run on innocuous commands, which is the archetypal
# "operator disables the gate" trainer.
#
# norm_cmd collapses whitespace runs and pads with single spaces, so `case`
# patterns can token-match. cmd_segments then splits a command into the units
# at which a NEW command can begin, and cmd_has_verb anchors each segment at
# its start.
#
# NO EXTERNAL BINARY IS USED BY ANY OF THE THREE [lens A F5]. The previous
# version ran `tr` inside a command substitution and `grep -qE` inside an
# `if` condition. Both contexts are exempt from `set -e`, and therefore from
# the ERR trap, so removing `grep` or `tr` from PATH turned EVERY command
# gate into a silent no-op: rc=0, no message, no log line, no hook_fail. That
# is the same T-1 class the secrets-gate header says was designed out ("a
# pure-bash `shopt` cannot fail open that way"); the lesson had been applied
# to the pattern matcher and not to these two shared helpers. Pure bash
# cannot fail open that way either.
#
# NEWLINE IS A COMMAND SEPARATOR [lens A F2]. `tr -s '[:space:]' ' '` turned
# `\\n` into a space while the anchor class was `[;&|(]`, which does not
# contain a space - so any verb on a second line was unreachable and
# `git add -A\\ngit commit -m wip` exited 0 on spec-gate-commit, test-gate and
# ci-mirror. Multi-line is the normal shape of an agent's Bash call, not an
# exotic one. norm_cmd now normalizes WITHIN lines and preserves the line
# structure; cmd_segments splits on newlines as well as `;&|()`.
#
# KNOWN AND ACCEPTED LIMITATION: a verb inside a quoted argument to another
# program - `sh -c "git commit"` - no longer matches. Substring matching did
# catch that, at the cost of every false positive above. Anchoring is the
# recommended trade in the upstream report; it is recorded here rather than
# left for the next reader to rediscover (docs/deferred-backlog.md J-1).

# norm_cmd "<cmd>" -> whitespace-normalized, one line per input line, each
# padded with single spaces so `case` patterns can token-match.
norm_cmd(){
  local _s="${1:-}" _line _out=""
  _s="${_s//$'\\t'/ }"; _s="${_s//$'\\r'/ }"
  _s="${_s//$'\\v'/ }"; _s="${_s//$'\\f'/ }"
  while [ "$_s" != "${_s//  / }" ]; do _s="${_s//  / }"; done
  while IFS= read -r _line; do
    _line="${_line# }"; _line="${_line% }"
    _out="$_out $_line "$'\\n'
  done <<< "$_s"
  printf '%s' "$_out"
  return 0
}

# cmd_segments "<cmd>" -> one SEGMENT per line: the units at which a new
# command can begin (newline, ; & | and parens), whitespace-normalized,
# padded, with any trailing `#` comment removed. This is the single
# segmentation mechanism in the suite - dependency-gate consumes it too.
#
# [round-2 review F-435] It is QUOTE-AWARE. It was not, and the same
# property was fail-CLOSED for dependency-gate (backlog J-7, accepted) and
# fail-OPEN here: a separator inside a quoted `git -c` option value tore the
# option run in half, so `git -c user.email="$(id -un)@h.com" commit` left
# the verb off command position and test-gate, spec-gate-commit and
# ci-mirror all exited 0. Only the fail-closed half was ever written down.
#
# Quote-awareness is the correct model, not a relaxation: a `;` inside a
# quoted argument is not a command separator to the shell either, so
# `git commit -m "fix; npm install evil"` SHOULD reach dependency-gate as
# one segment. Hiding an install inside quotes does not run it. J-7's
# over-match is therefore retired rather than traded away.
_CS_BT='`'
_CS_SEP=$'\\001'                 # segment break (never a byte a command uses)
_CS_WS=$'\\002'                  # whitespace INSIDE a quoted run
# [round-4 D5] Backslash escapes, parked as sentinels BEFORE the quote walk
# and restored one level when a run is handed to the invoker rule. Neither
# substrate's quote scanner handled `\\` at all, which is D5's actual root
# cause - an earlier diagnosis blamed recursion depth, a reviewer implemented
# depth-3 recursion, and two of D5's three reproductions still allowed:
#   bash -c "sh -c \\"pip install evil\\""   the \\" desynced the scanner, so
#                                          the outer run was read as `sh -c \\`
#   sh -c pip\\ install\\ evil               has no quoted run to recurse INTO
# Recursion over mis-parsed input is worse than no recursion, so the scanner
# is fixed first and depth is added after.
# [round-4 D5] How many times an invoker's argument is re-expanded, with the
# invoker test RE-APPLIED at each level. Stated once per substrate; the SDK's
# _EXPAND_DEPTH must equal it, and tests/test_composition.py asserts that the
# two literals agree.
#
# The round-4 brief prescribes 2, on a measurement that "depth 3 added nothing
# observable" - taken against the BROKEN scanner, which had already mis-parsed
# the third level away. With the scanner fixed, 3 is what reaches the corpus's
# NST-01, three nested shells, recorded as PROVEN TO EXECUTE. 4 was BUILT AND
# MEASURED on both substrates and changed no verdict on the round-4 probe
# corpus; a fourth level needs four nested quoting contexts, which no
# reachable spelling produces.
_CS_DEPTH=3
_CS_ESC=$'\\003'                 # a literal backslash
_CS_EDQ=$'\\004'                 # an escaped double quote
_CS_ESQ=$'\\005'                 # an escaped single quote
_CS_ESP=$'\\006'                 # an escaped space
_CS_BUF=""
_CS_EXTRA=""
# [round-4 D17] `_CS_INVOKERS` used to live here: emitted into every hook,
# ZERO call sites, and already drifted (it was missing `su`). A second, silent
# invoker list whose only effect was to make the count of them look smaller.
# Deleted. The live sets are interpolated from lib/cmdpos.py, once.
# Both helpers return through the global `_CS_R`, never through stdout.
# [round-4, measured] A `$(...)` helper here costs a FORK PER CALL: 2.4 ms and
# 18.8 s of system time over 20,000 calls, the same class as the 22.9 s
# `basename` regression F-937. Setting a global is 0.2 ms. Every helper on this
# path is written this way; do not "simplify" one back into a subshell.
_CS_R=""
_cs_esc_park(){                 # \\x -> sentinel, so quotes cannot be forged
  _CS_R="$1"
  case "$_CS_R" in *\\\\*) ;; *) return 0 ;; esac
  _CS_R="${_CS_R//\\\\\\\\/$_CS_ESC}"   # \\\\ first, or it eats the next rule's slash
  _CS_R="${_CS_R//\\\\\\"/$_CS_EDQ}"
  _CS_R="${_CS_R//\\\\\\'/$_CS_ESQ}"
  _CS_R="${_CS_R//\\\\ /$_CS_ESP}"
  return 0
}
_cs_esc_restore(){              # sentinel -> the character it stood for
  _CS_R="$1"
  case "$_CS_R" in
    *$_CS_ESC*|*$_CS_EDQ*|*$_CS_ESQ*|*$_CS_ESP*) ;;
    *) return 0 ;;
  esac
  _CS_R="${_CS_R//$_CS_EDQ/\\"}"; _CS_R="${_CS_R//$_CS_ESQ/\\'}"
  _CS_R="${_CS_R//$_CS_ESP/ }";  _CS_R="${_CS_R//$_CS_ESC/\\\\}"
  return 0
}
_cs_ops(){                      # operator -> segment break, UNQUOTED text only
  local _t="$1"
  _t="${_t//;/$_CS_SEP}"; _t="${_t//&/$_CS_SEP}"; _t="${_t//|/$_CS_SEP}"
  _t="${_t//"("/$_CS_SEP}"; _t="${_t//")"/$_CS_SEP}"
  # A backtick substitution runs its contents, so it opens a command
  # position, exactly as `$( )` does.
  _t="${_t//$_CS_BT/$_CS_SEP}"
  # [round-3 lens A, A5] An UNQUOTED newline is a command separator; a
  # newline INSIDE a quoted run is not, and the segment break is no longer
  # spelled with a newline so the two can finally be told apart. The old
  # code translated operators to `\\n` and then split the buffer on every
  # `\\n`, so a newline inside a quoted `git -c` value tore the segment in
  # half and `git -c a.b="p<newline>q" commit` escaped the anchor on
  # test-gate, eval-gate, ci-mirror and dependency-gate. F-435 fixed the
  # `;` half of that property and left the `\\n` half open, while
  # secrets-gate's twin fix carried quote state across newlines - two
  # parsers giving opposite answers about one character.
  _t="${_t//$'\\n'/$_CS_SEP}"
  _CS_BUF="$_CS_BUF$_t"
  return 0
}
# Is the segment currently being built headed by a shell INVOKER? Its
# quoted argument is then a command line, not data, and has to be
# segmented as one [round-3 lens A, A1]. Mirrors _sg_push's rule in
# secrets-gate; that rule was added there in the same batch and NOT here,
# which is what reopened `sh -c 'true; pip install evil'`.
#
# [round-4 D1/D2/D7] THE BOUND IS GONE. This walk used to stop at the first
# token that was not a prefix, not an assignment and not an invoker, so a
# wrapper carrying its OWN operand hid the invoker behind it: `timeout 5 sh -c`
# returned false because `5` is none of those, and `_CS_EXTRA` never received
# the run. `nohup sh -c` (no operand) denied correctly, which is what made the
# gap look like a missing binary name rather than a missing model.
#
# The replacement is NOT an arity table. A reviewer built one and measured 16
# of 27 real wrapper-flag spellings regressing from deny to allow - mostly LONG
# forms (`sudo --chroot /`, `nice --adjustment 5`, `flock --timeout 10`) of
# flags whose short form was in the table. Any such table has that hole and the
# next coreutils release reopens it silently.
#
# Instead: once a WRAPPER WORD has been seen, skip tokens until an invoker
# turns up or the segment ends. Unbounded, no flags modelled. The gate on
# `_seen` is the whole safety argument - `grep -r sh file` never starts the
# skip, because `grep` is not a wrapper - and over-consumption is the safe
# direction for a deny-list anyway.
_cs_isinv(){
  local _tail="${_CS_BUF##*$_CS_SEP}" _w _b _seen=0
  while : ; do
    _tail="${_tail#"${_tail%%[![:space:]]*}"}"
    _w="${_tail%%[[:space:]]*}"
    [ -z "$_w" ] && return 1
    _b="${_w##*/}"
    # An invoker is tested FIRST, so a DUAL word (watch/xargs/ssh - both a
    # transparent prefix and a thing whose argument is a command line) reports
    # true here while still leaving the head scannable for the anchor.
    case "$_b" in
      @@INV_CASE@@) return 0 ;;
    esac
    case "$_b" in
      @@PFX_CASE@@) _seen=1 ;;
      [A-Za-z_]*=*) _seen=1 ;;
      -*) ;;                     # a flag: never the command word
      *) [ "$_seen" = "1" ] || return 1 ;;
    esac
    _tail="${_tail#"$_w"}"
  done
}
_cs_scan(){
  local _s _pre _q _rest _run _pd _ps _tok _rem
  _s="$1"
  # Walk quoted runs the way secrets-gate's _sg_scan does, translating
  # operators in the UNQUOTED stretches only. Run-at-a-time, not
  # character-at-a-time: a per-character loop is O(n^2) under bash's
  # substring expansion, and F-937 is what that costs on a large command.
  while : ; do
    case "$_s" in *[\\"\\']*) ;; *) _cs_ops "$_s"; break ;; esac
    _pd="${_s%%\\"*}"; _ps="${_s%%\\'*}"
    if [ "${#_pd}" -le "${#_ps}" ]; then _q='"'; _pre="$_pd"
    else _q="'"; _pre="$_ps"; fi
    _cs_ops "$_pre"
    _rest="${_s#*"$_q"}"
    case "$_rest" in
      *"$_q"*) _run="${_rest%%"$_q"*}"; _s="${_rest#*"$_q"}" ;;
      *)       _run="$_rest"; _s="" ;;   # unterminated quote: take the rest
    esac
    # An invoker's argument is a command line: segment it too. Additive, so
    # the run also stays part of its own segment. [round-4 D5] The run is
    # UN-parked one level before it is handed on, which is what shell quote
    # removal does and what lets the next level see the inner quotes of
    # `bash -c "sh -c \\"pip install evil\\""`.
    if _cs_isinv; then
      _cs_esc_restore "$_run"
      _CS_EXTRA="$_CS_EXTRA$_CS_SEP$_CS_R"
    fi
    # Whitespace inside the run becomes a NON-space sentinel so the run
    # stays ONE token: every consumer's option-run and assignment patterns
    # are built from `[^ ]+`, and a quoted value containing a space
    # otherwise ends the run early. The quote characters themselves are
    # dropped, which additionally makes `"pip" install evil` and
    # `p''ip install evil` reach the tool matcher [round-3 lens A, A5].
    _run="${_run//$'\\n'/$_CS_WS}"; _run="${_run// /$_CS_WS}"
    _run="${_run//$'\\t'/$_CS_WS}"
    _CS_BUF="$_CS_BUF$_run"
    if [ -z "$_s" ]; then break; fi
  done
  # [round-4 D5, third reproduction] `sh -c pip\\ install\\ evil` has NO quoted
  # run to recurse into - the argument is one shell word held together by
  # backslashes - so the loop above never fires and the invoker rule never saw
  # it. A parked escaped space is exactly the marker for that shape.
  if _cs_isinv; then
    _rem="${_CS_BUF##*$_CS_SEP}"
    while [ -n "$_rem" ]; do
      _rem="${_rem#"${_rem%%[![:space:]]*}"}"
      _tok="${_rem%%[[:space:]]*}"
      [ -z "$_tok" ] && break
      case "$_tok" in
        *$_CS_ESP*)
          _cs_esc_restore "$_tok"
          _CS_EXTRA="$_CS_EXTRA$_CS_SEP$_CS_R" ;;
      esac
      _rem="${_rem#"$_tok"}"
    done
  fi
  return 0
}
cmd_segments(){
  local _s _seg _extra _depth
  _s="$(norm_cmd "${1:-}")"
  # The sentinels are ours; a command containing one would otherwise be able
  # to forge a segment break, glue two tokens together, or impersonate an
  # escape.
  _s="${_s//$_CS_SEP/ }"; _s="${_s//$_CS_WS/ }"
  _s="${_s//$_CS_ESC/ }"; _s="${_s//$_CS_EDQ/ }"
  _s="${_s//$_CS_ESQ/ }"; _s="${_s//$_CS_ESP/ }"
  _CS_BUF=""; _CS_EXTRA=""
  _cs_esc_park "$_s"
  _cs_scan "$_CS_R"
  # [round-4 D5] RECURSION, DEPTH 2, re-applying the invoker test at each
  # level. Depth 3 was implemented and measured to add nothing observable.
  #
  # The thing that is easy to get wrong here, and that would be worse than
  # leaving D5 open: expanding EVERY quoted run instead of re-applying the
  # invoker test. That re-opens J-7 and lens B finding 4 wholesale - prose in
  # a commit message becoming candidate paths - in the gate with no override
  # path. `_cs_scan` re-tests `_cs_isinv` per level for exactly that reason.
  #
  # Ordering note: this multiplies segment count on invoker-heavy input, so it
  # lands AFTER the secrets-gate cost work, not before it.
  _depth=0
  while [ -n "$_CS_EXTRA" ] && [ "$_depth" -lt "$_CS_DEPTH" ]; do
    _extra="$_CS_EXTRA"; _CS_EXTRA=""
    _cs_ops "$_extra"
    _cs_esc_park "$_extra"
    _cs_scan "$_CS_R"
    _depth=$((_depth + 1))
  done
  if [ -n "$_CS_EXTRA" ]; then _cs_ops "$_CS_EXTRA"; fi
  while IFS= read -r -d "$_CS_SEP" _seg || [ -n "$_seg" ]; do
    _seg="${_seg%% \\#*}"
    _seg="${_seg//$'\\n'/ }"
    _cs_esc_restore "$_seg"; _seg="$_CS_R"
    _seg="${_seg# }"; _seg="${_seg% }"
    [ -z "$_seg" ] && continue
    printf ' %s \\n' "$_seg"
  done <<< "$_CS_BUF"
  return 0
}

# Command-position prefixes that do not change WHICH program runs.
#
# [round-2 review F-401] Redirections, brace groups and shell keywords each
# evaded the anchor with ONE token while a bare `pip install evil` was denied.
#
# [round-4 D9/D3] POSITIONALS. This anchor UNDER-consumed, and that is the
# fail-open direction. `(env|sudo|doas|su)( +-[^ ]+)* +` could take the flag
# but never its value, so `sudo -u root pip install evilpkg` was rc=0 - on
# BOTH substrates, at ALL THREE commits, which is why neither a substrate
# differential nor a parent-vs-head sweep could see it. Same for `timeout 5`,
# `nice -n 5`, `flock /tmp/l`, `chroot /`.
#
# A wrapper word may now be followed by any run of flags and positionals. That
# is unbounded on purpose - see lib/cmdpos.py for why an arity table was
# measured to LOSE 16 of 27 real spellings - and it cannot fail open, because
# regex matching asks whether a parse EXISTS: a run that greedily swallows the
# command word backtracks. Verified: `sudo -i pip install evil` matches
# (`-i` takes no value), `timeout -k 1 -s KILL 5 pip install evil` matches,
# and `echo -n pip install evil` does NOT, because `echo` is not a wrapper so
# the run never starts. That last case is the whole safety argument.
#
# The word lists are interpolated from lib/cmdpos.py. They used to be written
# out here AND in _cs_isinv AND in secrets-gate's _sg_push AND in three more
# places on the SDK side; D3 is what one of those copies not growing looks
# like from the outside.
CMD_PFX='@@ANCHOR_ERE@@'

# cmd_has_verb "<normalized cmd>" "<tool regex>" "<subcommand regex>"
# True if the command invokes `<tool> <subcommand>` at a command position.
# The tool may carry a path (`/usr/bin/git commit`).
cmd_has_verb(){
  local _re="^ *${CMD_PFX}([^ ]*/)?$2( +-[Cc] +[^ ]+| +-[^ ]+)* +$3( |\\$)"
  local _seg
  # `if`, not `[[ ]] && return` - a failing `&&` list as the last command of
  # a loop body trips `set -e` and would route every NON-match through the
  # ERR trap into hook_fail.
  while IFS= read -r _seg; do
    if [[ "$_seg" =~ $_re ]]; then return 0; fi
  done < <(cmd_segments "$1")
  return 1
}

# git_verb "<normalized cmd>" "commit" - the common case.
git_verb(){ cmd_has_verb "$1" "git" "$2"; }
"""

# [round-4 D3] The one place the shell substrate's command-position sets are
# written. Every `@@NAME@@` above is filled here, from lib/cmdpos.py, so the
# shell walker, the shell anchor and secrets-gate's walker cannot drift apart
# again - which is precisely what D3 was.
#
# `.replace` rather than an f-string: `_HOOK_HEADER` is 300 lines of shell and
# making it an f-string would mean doubling every `${...}` in it, a diff with
# far more risk than value.
_SHELL_SUBST = {
    "@@INV_CASE@@": cmdpos.bash_case_alt(cmdpos.ALL_INVOKERS, "      "),
    "@@PFX_CASE@@": cmdpos.bash_case_alt(cmdpos.ALL_PREFIXES, "      "),
    "@@ANCHOR_ERE@@": cmdpos.anchor_regex(),
    "@@PIPE_ERE@@": cmdpos.pipe_to_shell_regex(),
    "@@RUNNERS_ERE@@": cmdpos.runners_regex(),
    "@@DL_CASE@@": cmdpos.bash_case_alt(cmdpos.DOWNLOADERS, "      "),
    "@@INT_CASE@@": cmdpos.alt(cmdpos.INTERPRETERS),
}
# The header carries the command-position model; the gate BODIES carry the
# arrival-channel patterns. Both are filled from _SHELL_SUBST - the split is
# only about which string each placeholder appears in - and each is asserted
# present where it belongs, so a renamed placeholder fails the import instead
# of silently emitting `@@PIPE_ERE@@` into a live hook.
_HEADER_PLACEHOLDERS = ("@@INV_CASE@@", "@@PFX_CASE@@", "@@ANCHOR_ERE@@")
for _k in _HEADER_PLACEHOLDERS:
    if _k not in _HOOK_HEADER:
        raise AssertionError(f"hook-header placeholder {_k} not found")
    _HOOK_HEADER = _HOOK_HEADER.replace(_k, _SHELL_SUBST[_k])


