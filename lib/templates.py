    if not greenfield.startswith(_HOOK_HEADER):
        # [round-4] This WAS a `return greenfield` labelled "defensive: if
        # _hook_body ever stops prefixing _HOOK_HEADER, this returns the body
        # unchanged rather than breaking". It did not break - it silently
        # dropped the retrofit preamble from all three retrofit hooks the
        # moment the header stopped matching byte-for-byte, which happened as
        # soon as the header gained an emission-time placeholder. The legacy
        # allowlist simply stopped existing, and only ONE retrofit test
        # noticed. A wrong composition is not a safe fallback.
        raise AssertionError(
            f"retrofit hook {name}: greenfield body does not start with "
            f"_HOOK_HEADER; the splice below would drop the retrofit "
            f"preamble silently")
